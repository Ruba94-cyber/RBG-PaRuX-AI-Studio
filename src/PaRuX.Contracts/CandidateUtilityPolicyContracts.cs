namespace PaRuX.Contracts;

/// <summary>
/// Explicit inputs required before a capability-scoped Candidate utility comparison can be
/// evaluated. Its only quality evidence is the exact fixed smoke profile below, not a user-facing
/// execution profile or broad capability claim. This contract defines no defaults and is not evidence.
/// </summary>
public sealed class CandidateUtilityPolicyDefinition
{
    public const int CurrentSchemaVersion = 4;

    public int SchemaVersion { get; set; } = CurrentSchemaVersion;
    public string PolicyId { get; set; } = string.Empty;
    public string Capability { get; set; } = string.Empty;
    public string QualitySuiteId { get; set; } = string.Empty;
    public int QualitySuiteVersion { get; set; }
    /// <summary>Exact fixed evaluation profile, separate from the user-facing execution profile.</summary>
    public string QualityEvidenceProfileId { get; set; } = string.Empty;
    public int QualityEvidenceProfileVersion { get; set; }
    public string QualityEvidenceProfileSha256 { get; set; } = string.Empty;
    public string PerformanceWorkloadId { get; set; } = string.Empty;
    public int PerformanceWorkloadVersion { get; set; }

    /// <summary>Exact environment scope for a calibrated policy; all values must match the measured evidence.</summary>
    public string HardwareFingerprint { get; set; } = string.Empty;
    public string RuntimeFingerprint { get; set; } = string.Empty;
    public string BinaryFingerprint { get; set; } = string.Empty;
    public string ConfigurationFingerprint { get; set; } = string.Empty;

    /// <summary>Minimum task-quality pass rate in basis points (1..10000).</summary>
    public int? MinimumQualityPassRateBasisPoints { get; set; }

    /// <summary>Minimum measured quality reliability in basis points (1..10000).</summary>
    public int? MinimumQualityReliabilityBasisPoints { get; set; }

    /// <summary>Named, versioned reliability estimator; unknown estimators are never interchangeable.</summary>
    public string QualityReliabilityEstimatorId { get; set; } = string.Empty;

    /// <summary>Distinct fully-scoped quality-run records required before the reliability floor is assessed.</summary>
    public int? MinimumQualityRunCount { get; set; }

    /// <summary>Exact comparable performance metric and unit; direction is explicit.</summary>
    public string PerformanceMetricId { get; set; } = string.Empty;
    public string PerformanceMetricUnit { get; set; } = string.Empty;
    public bool? HigherPerformanceMetricIsBetter { get; set; }

    /// <summary>Exact second required response-speed dimension. Always lower-is-better.</summary>
    public string TimeToFirstTokenMetricId { get; set; } = string.Empty;
    public string TimeToFirstTokenMetricUnit { get; set; } = string.Empty;
    public int? MinimumTimeToFirstTokenMarginBasisPoints { get; set; }

    /// <summary>Legacy v3 utility margin retained for history; never used by the v4 evaluator.</summary>
    public int? MinimumUtilityMarginBasisPoints { get; set; }

    /// <summary>Required lower-is-better completion-latency margin, in basis points.</summary>
    public int? MinimumCompletionLatencyMarginBasisPoints { get; set; }
}

/// <summary>Readiness returned by Core for its explicitly configured Candidate utility policy.</summary>
public sealed record CandidateUtilityPolicyStatus(
    bool Configured,
    string Readiness,
    string ReasonCode,
    CandidateUtilityPolicyDefinition? Policy);

/// <summary>
/// Current Core-owned evidence scope for explicitly configuring comparison criteria. Fingerprints
/// are generated by Core and must be echoed unchanged when saving so stale runtime context fails closed.
/// </summary>
public sealed record CandidateUtilityPolicyCalibrationContext(
    string ContextFingerprint,
    string Capability,
    string QualitySuiteId,
    int QualitySuiteVersion,
    string QualityProfileId,
    int QualityProfileVersion,
    string QualityProfileSha256,
    string PerformanceWorkloadId,
    int PerformanceWorkloadVersion,
    string PerformanceWorkloadSha256,
    CandidateEvaluationEnvironment QualityEnvironment,
    CandidateEvaluationEnvironment PerformanceEnvironment,
    int MaximumQualityRunCount,
    int MaximumMarginBasisPoints);

/// <summary>
/// Explicit user-chosen comparison floors and speed margins. Scope and machine/runtime fingerprints
/// are deliberately not user supplied; Core derives and validates them from the current environment.
/// All nullable values are required and absent values are rejected.
/// </summary>
public sealed record CandidateUtilityPolicyConfigurationRequest(
    string ContextFingerprint,
    int? MinimumQualityPassRateBasisPoints,
    int? MinimumQualityReliabilityBasisPoints,
    int? MinimumQualityRunCount,
    int? MinimumTimeToFirstTokenMarginBasisPoints,
    int? MinimumCompletionLatencyMarginBasisPoints,
    string? QualityProfileId = null);

/// <summary>Manual request to compare stored evidence for one exact managed Candidate.</summary>
public sealed record CandidateUtilityComparisonRequest(string CandidateKey, string ManagedFileName);

/// <summary>
/// A guarded evidence comparison only. Even a positive disposition requires human review and has no
/// recommendation, activation, promotion or routing authority.
/// </summary>
public sealed record CandidateUtilityComparisonResponse(
    string Disposition,
    string ReasonCode,
    string? Capability,
    bool RequiresHumanReview,
    bool IsRecommendation,
    bool PromotionPerformed,
    bool RoutingChanged,
    string Interpretation,
    string? ManualPinReason = null);

/// <summary>
/// Reliability estimator identifiers accepted by the policy contract. The supported estimator is an
/// observed fresh-process suite pass rate, not a statistical confidence guarantee or an independent sample
/// of model capability. Its evaluator must use unique, fully-scoped run records and count failed attempts
/// in the matching cohort as non-successes.
/// </summary>
public static class CandidateQualityReliabilityEstimator
{
    public const string FreshProcessSuitePassRateV1 = "fresh-process-suite-pass-rate.v1";
}

/// <summary>Exact metric identifiers and units emitted by the built-in Candidate workload.</summary>
public static class CandidatePerformanceMetric
{
    public const string PromptTokensPerSecondId = "prompt_tok_per_s";
    public const string DecodeTokensPerSecondId = "decode_tok_per_s";
    public const string CompletionMillisecondsId = "completion_ms";
    public const string TimeToFirstTokenMillisecondsId = "ttft_ms";
    public const string TokensPerSecondUnit = "tokens/s";
    public const string MillisecondsUnit = "ms";
}
