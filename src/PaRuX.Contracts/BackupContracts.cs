using System;

namespace PaRuX.Contracts;

/// <summary>
/// Describes what a PaRuX backup archive contains and which format version produced it, so a
/// future PaRuX version can detect an older (or newer) backup and either handle it or refuse it
/// cleanly instead of guessing at its shape. Serialized as "manifest.json" at the root of the
/// backup .zip - see BackupService (PaRuX.Server) for how the archive itself is assembled.
/// </summary>
public sealed class BackupManifest
{
    /// <summary>Bump this only when the archive's on-disk shape changes in a way older code
    /// can't read (e.g. a renamed entry, a changed DB schema baked into the file). Adding an
    /// optional field does not require a bump.</summary>
    public int FormatVersion { get; set; } = 1;

    public DateTime CreatedUtc { get; set; }

    /// <summary>PaRuX.Server's own assembly version at export time - informational only,
    /// never used to gate whether a restore is allowed (FormatVersion is what gates that).</summary>
    public string AppVersion { get; set; } = string.Empty;

    public string MachineName { get; set; } = string.Empty;

    public BackupContents Contents { get; set; } = new();
}

/// <summary>Which of PaRuX's own data categories this backup includes, plus a quick count of
/// each for the confirmation UI - never the indexed-folder file contents or downloaded AI models,
/// which stay on disk where they already are and are out of scope for a backup.</summary>
public sealed class BackupContents
{
    public bool ConversationsIncluded { get; set; }
    public int ConversationCount { get; set; }

    public bool MemoryIncluded { get; set; }
    public int MemoryCount { get; set; }

    /// <summary>Only the configured folder paths/enabled flags, never the indexed chunks or
    /// embeddings for them - those are large, fully derived from the user's own files on disk,
    /// and are regenerated by a normal reindex after restore.</summary>
    public bool RagSourcesIncluded { get; set; }
    public int RagSourceCount { get; set; }

    /// <summary>The desktop client's own settings.json (theme, hotkey, quotas, etc.) - absent
    /// only if no client has ever run on this machine yet, e.g. a server-only export.</summary>
    public bool SettingsIncluded { get; set; }

    /// <summary>Multi-Agent Orchestrator task graph (TaskStore/orchestrator.db) - queued/running/
    /// completed agent tasks, their dependency edges and logs.</summary>
    public bool TasksIncluded { get; set; }
    public int TaskCount { get; set; }

    /// <summary>Local Context Graph (ContextGraphStore/context-graph.db) - entities/relations
    /// learned from chat and used for retrieval.</summary>
    public bool ContextGraphIncluded { get; set; }
    public int ContextGraphEntityCount { get; set; }

    /// <summary>Artifact Workspace metadata and version history (ArtifactStore/artifacts.db) -
    /// not the underlying content each version's ContentRef points at, same scope boundary as
    /// RAG source contents being excluded.</summary>
    public bool ArtifactsIncluded { get; set; }
    public int ArtifactCount { get; set; }

    /// <summary>Configured Automations and their last-triggered state (AutomationStore/
    /// automations.db).</summary>
    public bool AutomationsIncluded { get; set; }
    public int AutomationCount { get; set; }

    /// <summary>Autopilot run history (AutopilotStore/autopilot.db) - goals, retry counts,
    /// final reports.</summary>
    public bool AutopilotRunsIncluded { get; set; }
    public int AutopilotRunCount { get; set; }

    /// <summary>Eval/Regression Lab datasets, cases and run history (EvalStore/eval.db).</summary>
    public bool EvalIncluded { get; set; }
    public int EvalDatasetCount { get; set; }

    /// <summary>Adapter Manager's registry (AdapterStore/adapters.db) - not the adapter files
    /// themselves, same as every other store here: metadata only, large binary payloads stay on
    /// disk where they already are.</summary>
    public bool AdaptersIncluded { get; set; }
    public int AdapterCount { get; set; }

    /// <summary>PaRuX AutoLab's experiment records (AutoLabStore/autolab.db) - which real model
    /// each Eval Lab run was captured against, not the eval data itself (already covered above).</summary>
    public bool AutoLabIncluded { get; set; }
    public int ExperimentCount { get; set; }

    /// <summary>Workflow Builder's saved templates (WorkflowStore/workflows.db) - the templates
    /// themselves, not the real AgentTasks a run of one creates (those already live in
    /// orchestrator.db, covered above).</summary>
    public bool WorkflowsIncluded { get; set; }
    public int WorkflowCount { get; set; }

    /// <summary>Empirical Model Capability Profiler run history (CapabilityProfilerStore/
    /// capability-profiles.db) - the probe verdicts, not the models themselves.</summary>
    public bool CapabilityProfilesIncluded { get; set; }
    public int CapabilityProfileRunCount { get; set; }

    /// <summary>2026-08-27 Backup/Restore re-audit: text-role assignments (which GGUF backs
    /// standard/fast/reasoning/planner/coding/reviewer/vision/uncensored), media-checkpoint
    /// overrides (image/image_edit/video), and the Smart Router's candidate pools
    /// (LocalAiPaths.ExportBackupConfig) - real user configuration that was previously silently
    /// lost on restore, forcing every role/candidate assignment to be redone by hand. Deliberately
    /// still excludes ModelDownloadService's own alias labels (cosmetic only, already disclosed
    /// elsewhere as harmless if lost) and the machine-specific LocalAI install root path (restoring
    /// a path from a different machine would be actively wrong, not helpful) - both real, disclosed,
    /// separate follow-ups, not silently dropped.</summary>
    public bool LocalAiRoleConfigIncluded { get; set; }

    /// <summary>2026-08-27 Backup/Restore re-audit: native llama-bench run history
    /// (ModelBenchmarkStore/model-benchmarks.db) - previously the only vNext-era SQLite store
    /// missing the standard BackupDatabaseTo/ReplaceDatabaseFile pair every other store here
    /// already has.</summary>
    public bool ModelBenchmarksIncluded { get; set; }
    public int ModelBenchmarkRunCount { get; set; }

    /// <summary>2026-08-27 Backup/Restore re-audit: user-created personas and the active selection
    /// (PersonaService/personas.json). Restoring updates the live in-memory cache immediately, not
    /// just the file, so an already-running server serves the restored personas without a
    /// restart.</summary>
    public bool PersonasIncluded { get; set; }
    public int CustomPersonaCount { get; set; }

    /// <summary>2026-08-27 Backup/Restore re-audit: configured external MCP servers
    /// (McpClientRegistry/mcp-clients.json). Restoring disconnects every currently-live MCP
    /// connection first (an old connection may point at config this restore is about to replace
    /// or remove entirely), then updates the live in-memory cache and persists to disk.</summary>
    public bool McpClientsIncluded { get; set; }
    public int McpClientCount { get; set; }

    /// <summary>2026-08-27 Backup/Restore re-audit: the opt-in internet-access toggle
    /// (InternetSettingsService/internet.json). Absent only if this setting has never been
    /// explicitly touched on this machine (still the untouched, disabled-by-default state).</summary>
    public bool InternetSettingIncluded { get; set; }

    /// <summary>2026-08-27 Backup/Restore re-audit: cosmetic display-name aliases for managed
    /// GGUF files (ModelDownloadService/.aliases.json, under ModelsDirectory - not
    /// ServerState.StateDirectory like every other entry here). Previously deliberately excluded
    /// as "harmless if lost"; closed for real per a follow-up user directive - purely cosmetic,
    /// every managed-library action still addresses files by their real FileName, never by alias,
    /// so a restored alias can never misdirect a delete/load/import.</summary>
    public bool ModelAliasesIncluded { get; set; }
    public int ModelAliasCount { get; set; }

    /// <summary>2026-08-27: which Hugging Face repo each managed GGUF was downloaded from
    /// (ModelDownloadService/.repo-ids.json, under ModelsDirectory - same seam as ModelAliases
    /// above), closing the License/Trust Manager's disclosed "installed-library backfill" gap.
    /// Purely metadata for license lookup, same non-load-bearing status as ModelAliases - every
    /// managed-library action still addresses files by their real FileName, never by RepoId.</summary>
    public bool ModelRepoIdsIncluded { get; set; }
    public int ModelRepoIdCount { get; set; }

    /// <summary>2026-09-24: immutable revision, publisher-declared licence/review snapshot and
    /// provider-hash verification evidence for completed managed model downloads. Model bytes
    /// themselves remain outside the backup; missing entries mean provenance is unknown.</summary>
    public bool ModelProvenanceIncluded { get; set; }
    public int ModelProvenanceEntryCount { get; set; }

    /// <summary>2026-08-27 Backup/Restore re-audit: paired LAN devices (RemoteAccessService/
    /// remote-access.json's Devices list). Each device's TokenHash is a one-way SHA256 hash of the
    /// real pairing token - the raw token is returned to the user exactly once at pairing
    /// completion and is never persisted anywhere, so exporting/reimporting the hash is safe;
    /// nothing secret is exposed by this backup entry. Restoring updates the live singleton
    /// immediately, not just the file.</summary>
    public bool PairedDevicesIncluded { get; set; }
    public int PairedDeviceCount { get; set; }

    /// <summary>2026-08-27 second re-audit pass (found by an independent full re-enumeration at
    /// the end of the first pass, not part of its original six-item list): user-created/imported
    /// Skills and per-skill enabled/disabled overrides (SkillRegistryService/skills.db). Built-in
    /// Skills themselves are never included - they load read-only from skills/built-in/*.json next
    /// to the server binary, not from this database.</summary>
    public bool SkillsIncluded { get; set; }
    public int UserSkillCount { get; set; }

    /// <summary>User-imported "bring your own" ComfyUI workflow templates
    /// (CustomWorkflowService/custom-workflows/) - distinct from Workflow Builder's own saved
    /// templates (WorkflowsIncluded above, a different feature). Captures both the index and each
    /// workflow's real ComfyUI graph JSON, not just the index metadata.</summary>
    public bool CustomWorkflowsIncluded { get; set; }
    public int CustomWorkflowCount { get; set; }

    /// <summary>The "auto-retry a refused STANDARD reply on UNCENSORED" preference
    /// (AiProfileService/auto-fallback.json) - a persisted boolean user setting, the same category
    /// as InternetSettingIncluded above, not the neighboring genuine LocalAI runtime state
    /// (mode.txt/active-profile.txt) which stays correctly excluded.</summary>
    public bool AutoFallbackSettingIncluded { get; set; }

    /// <summary>The user's own Remote Access Enabled/Port choice (RemoteAccessService/
    /// remote-access.json) - deliberately excludes Address, which is machine/network-specific and
    /// already self-heals via LoadConfiguration's own startup revalidation if it doesn't match a
    /// real private address on the machine being restored to.</summary>
    public bool RemoteAccessSettingsIncluded { get; set; }

    /// <summary>Cross-surface execution quality preference and evidence-backed model overrides.
    /// Stored as an optional JSON entry so format-v1 archives made before this field remain fully
    /// restorable, while new backups no longer lose user-tuned execution budgets.</summary>
    public bool ExecutionProfilesIncluded { get; set; }

    /// <summary>
    /// Visual/App Context V2 intentionally remains local to the workstation and is not copied into
    /// portable backups. It can contain full desktop screenshots, credentials or other information
    /// visible on screen, and its generated evidence has its own bounded retention policy. Restore
    /// therefore leaves the destination machine's existing Visual Context untouched instead of
    /// transferring screen history from another computer. Optional manifest fields keep older
    /// format-v1 archives compatible while making this privacy boundary explicit.
    /// </summary>
    public bool VisualContextIncluded { get; set; }

    public string VisualContextBackupPolicy { get; set; } = string.Empty;
}

/// <summary>Result of a POST /api/v1/backup/import call.</summary>
public sealed class BackupImportResult
{
    public bool Success { get; set; }
    public string Message { get; set; } = string.Empty;
    public BackupContents? Restored { get; set; }

    /// <summary>Path of the automatic pre-restore snapshot archive (kept for manual recovery).</summary>
    public string? RollbackSnapshotPath { get; set; }

    /// <summary>Live stores that could not be exported into the snapshot (missing/corrupt). They were restored
    /// without a rollback safety net; the caller had to opt in explicitly.</summary>
    public List<string> UnsnapshottableStores { get; set; } = new();
}

/// <summary>HTTP 409 body when a restore is refused because the rollback snapshot would be incomplete.</summary>
public sealed class BackupImportRefusal
{
    public const string IncompleteRollbackSnapshotCode = "incomplete-rollback-snapshot";
    public string Error { get; set; } = string.Empty;
    public string Code { get; set; } = IncompleteRollbackSnapshotCode;
    public List<string> UnsnapshottableStores { get; set; } = new();
}
